CREATE DATABASE IF NOT EXISTS stageconnect CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE stageconnect;

CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('student','recruiter','admin') NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE student_profiles (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 university VARCHAR(180) DEFAULT NULL,
 program VARCHAR(180) DEFAULT NULL,
 level VARCHAR(80) DEFAULT NULL,
 city VARCHAR(120) DEFAULT NULL,
 skills TEXT DEFAULT NULL,
 interests TEXT DEFAULT NULL,
 search_type ENUM('stage','alternance','both') NOT NULL DEFAULT 'both',
 bio TEXT DEFAULT NULL,
 cv_path VARCHAR(255) DEFAULT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_student FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE recruiter_profiles (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 company_name VARCHAR(190) NOT NULL DEFAULT '',
 sector VARCHAR(150) DEFAULT NULL,
 website VARCHAR(250) DEFAULT NULL,
 city VARCHAR(120) DEFAULT NULL,
 description TEXT DEFAULT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_recruiter FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE offers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 recruiter_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL,
 type ENUM('stage','alternance') NOT NULL,
 city VARCHAR(120) NOT NULL,
 description TEXT NOT NULL,
 requirements TEXT DEFAULT NULL,
 starts_on DATE DEFAULT NULL,
 ends_on DATE DEFAULT NULL,
 status ENUM('open','closed') NOT NULL DEFAULT 'open',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_offers (status,type,created_at),
 CONSTRAINT fk_offers_recruiter FOREIGN KEY (recruiter_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE applications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 offer_id BIGINT UNSIGNED NOT NULL,
 student_id BIGINT UNSIGNED NOT NULL,
 cover_letter TEXT DEFAULT NULL,
 status ENUM('pending','interview','rejected') NOT NULL DEFAULT 'pending',
 applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_application (offer_id,student_id),
 INDEX idx_applications_student (student_id,status),
 CONSTRAINT fk_application_offer FOREIGN KEY (offer_id) REFERENCES offers(id) ON DELETE CASCADE,
 CONSTRAINT fk_application_student FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 message VARCHAR(500) NOT NULL,
 link VARCHAR(250) DEFAULT NULL,
 is_read TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_notif (user_id,is_read,created_at),
 CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE activity_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor_id BIGINT UNSIGNED DEFAULT NULL,
 actor_email VARCHAR(190) DEFAULT NULL,
 action VARCHAR(100) NOT NULL,
 target_type VARCHAR(50) DEFAULT NULL,
 target_id BIGINT UNSIGNED DEFAULT NULL,
 details VARCHAR(500) DEFAULT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_logs_created (created_at),
 CONSTRAINT fk_log_actor FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
